/**
 * Re-import Adatvédelem from final-adatvedelem.html without touching Impresszum defaults.
 */
import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(__dirname, '..');
const outDir = path.join(root, 'src', 'content', 'jogi');

const adatPath =
  process.argv[2] ??
  path.join(process.env.USERPROFILE ?? '', 'Downloads', 'final-adatvedelem.html');

if (!fs.existsSync(adatPath)) {
  console.error('Missing:', adatPath);
  process.exit(1);
}

const impressumBody = fs.readFileSync(path.join(outDir, 'defaultImpressumBody.html'), 'utf8');
const adatHtml = fs.readFileSync(adatPath, 'utf8');

const adatLeadMatch = adatHtml.match(/<p class="hlead">([\s\S]*?)<\/p>/);
const adatLead = adatLeadMatch ? adatLeadMatch[1].trim() : '';
const gridIdx = adatHtml.indexOf('class="lgrid"');
if (gridIdx < 0) throw new Error('no lgrid in adatvedelem HTML');
const gridOpen = adatHtml.lastIndexOf('<div', gridIdx);
const gridClose = adatHtml.indexOf('</section>', gridIdx);
let adatBody = adatHtml.slice(gridOpen, gridClose);
adatBody = adatBody.replace(/^<div class="lgrid">/, '').replace(/<\/div>\s*$/, '').trim();
adatBody = adatBody.replace(/final-adatvedelem\.html/g, '/jogi/adatvedelem');
adatBody = adatBody.replace(/final-impresszum\.html/g, '/jogi/impresszum');

fs.writeFileSync(path.join(outDir, 'defaultAdatvedelemBody.html'), adatBody, 'utf8');
fs.writeFileSync(path.join(outDir, 'defaultAdatvedelemLead.txt'), adatLead, 'utf8');

const tsString = (value) => JSON.stringify(value);
const generated = `/** Generated by scripts/extract-jogi-html.mjs — do not edit by hand. */
export const defaultImpressumBodyHtml = ${tsString(impressumBody)};
export const defaultAdatvedelemBodyHtml = ${tsString(adatBody)};
export const defaultAdatvedelemHeroLead = ${tsString(adatLead)};
`;

fs.writeFileSync(path.join(outDir, 'jogiContent.generated.ts'), generated, 'utf8');
console.log('Adatvédelem imported from:', adatPath);
console.log('Impresszum preserved, length', impressumBody.length);
console.log('Adatvédelem body length', adatBody.length);
