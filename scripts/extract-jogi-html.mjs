import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(__dirname, '..');
const outDir = path.join(root, 'src', 'content', 'jogi');

const impressumPath =
  process.argv[2] ?? 'C:/Users/Erikk/Downloads/final-impresszum.html';
const adatPath =
  process.argv[3] ?? 'C:/Users/Erikk/Downloads/final-adatvedelem.html';

fs.mkdirSync(outDir, { recursive: true });

function extract(html, startMarker, endMarker) {
  const start = html.indexOf(startMarker);
  const end = html.indexOf(endMarker, start);
  if (start < 0 || end < 0) {
    throw new Error(`markers not found: ${startMarker}`);
  }
  let chunk = html.slice(start + startMarker.length, end).trim();
  chunk = chunk.replace(/final-adatvedelem\.html/g, '/jogi/adatvedelem');
  chunk = chunk.replace(/final-impresszum\.html/g, '/jogi/impresszum');
  return chunk;
}

if (!fs.existsSync(impressumPath)) {
  console.error('Missing:', impressumPath);
  process.exit(1);
}
const impHtml = fs.readFileSync(impressumPath, 'utf8');
const adatHtml = fs.readFileSync(adatPath, 'utf8');
const legalIdx = impHtml.indexOf('class="legal"');
console.log('legal idx', legalIdx, impHtml.slice(legalIdx - 5, legalIdx + 20));

const impressumStart = impHtml.indexOf('class="legal"');
if (impressumStart < 0) throw new Error('no legal');
const impressumOpen = impHtml.lastIndexOf('<div', impressumStart);
const impressumClose = impHtml.indexOf('</section>', impressumStart);
let impressumBody = impHtml.slice(impressumOpen, impressumClose);
impressumBody = impressumBody.replace(/^<div class="legal">/, '').replace(/<\/div>\s*$/, '').trim();
impressumBody = impressumBody.replace(/final-adatvedelem\.html/g, '/jogi/adatvedelem');
impressumBody = impressumBody.replace(/final-impresszum\.html/g, '/jogi/impresszum');
const adatLeadMatch = adatHtml.match(/<p class="hlead">([\s\S]*?)<\/p>/);
const adatLead = adatLeadMatch ? adatLeadMatch[1].trim() : '';
const gridIdx = adatHtml.indexOf('class="lgrid"');
const gridOpen = adatHtml.lastIndexOf('<div', gridIdx);
const gridClose = adatHtml.indexOf('</section>', gridIdx);
let adatBody = adatHtml.slice(gridOpen, gridClose);
adatBody = adatBody.replace(/^<div class="lgrid">/, '').replace(/<\/div>\s*$/, '').trim();
adatBody = adatBody.replace(/final-adatvedelem\.html/g, '/jogi/adatvedelem');
adatBody = adatBody.replace(/final-impresszum\.html/g, '/jogi/impresszum');

fs.writeFileSync(path.join(outDir, 'defaultImpressumBody.html'), impressumBody, 'utf8');
fs.writeFileSync(path.join(outDir, 'defaultAdatvedelemBody.html'), adatBody, 'utf8');
fs.writeFileSync(path.join(outDir, 'defaultAdatvedelemLead.txt'), adatLead, 'utf8');

function tsString(value) {
  return JSON.stringify(value);
}

const generated = `/** Generated by scripts/extract-jogi-html.mjs — do not edit by hand. */
export const defaultImpressumBodyHtml = ${tsString(impressumBody)};
export const defaultAdatvedelemBodyHtml = ${tsString(adatBody)};
export const defaultAdatvedelemHeroLead = ${tsString(adatLead)};
`;

fs.writeFileSync(path.join(outDir, 'jogiContent.generated.ts'), generated, 'utf8');
console.log('Wrote jogi defaults:', impressumBody.length, adatBody.length);
